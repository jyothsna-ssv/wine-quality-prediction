import argparse
import setuptools
from pyspark.sql import SparkSession
from pyspark.sql.functions import col, log, when, udf
from pyspark.sql.types import DoubleType
from pyspark.ml.feature import VectorAssembler, MinMaxScaler
from pyspark.ml import Pipeline, PipelineModel
from pyspark.ml.evaluation import MulticlassClassificationEvaluator
from pyspark.ml.feature import VectorAssembler
from functools import reduce

# UDF to extract scaled vector value
unlist = udf(lambda x: float(list(x)[0]), DoubleType())

# Paths (modify as needed)
DEFAULT_VALIDATE_DATA_PATH = "s3://wine-ml-jk773/input-data/ValidationDataset.csv"
DEFAULT_MODEL_PATH = "s3://wine-ml-jk773/models/wine_rf_model"

parser = argparse.ArgumentParser(description='Wine Quality Prediction')
parser.add_argument('--input_csv', default=DEFAULT_VALIDATE_DATA_PATH, help='Path to the CSV file for prediction')
parser.add_argument('--model-path', default=DEFAULT_MODEL_PATH,
                    help='Directory where the trained model is saved')
args = parser.parse_args()

input_csv = args.input_csv
model_path = args.model_path

spark = SparkSession.builder.appName('WineModelPrediction').getOrCreate()

# Load and clean column names
val_df = spark.read.option("header", True).option("sep", ";").csv(input_csv)
old_cols = val_df.columns
clean_cols = [c.replace('"', '') for c in old_cols]
val_df = reduce(lambda df, i: df.withColumnRenamed(old_cols[i], clean_cols[i]),
                range(len(clean_cols)), val_df)

# Cast to double and remove duplicates
val_df = (val_df
          .select(*[col(c).cast("double").alias(c) for c in clean_cols])
          .distinct())

# Create categorical label (for evaluation)
val_df = val_df.withColumn(
    "quality_label",
    when(col("quality") <= 4, "Low")
    .when(col("quality") <= 7, "Medium")
    .otherwise("High")
)

# Log-transform selected features
for feat in ("sulphates", "alcohol"):
    val_df = val_df.withColumn(f"log_{feat}", log(col(feat) + 1))

# Identify features to scale
feature_cols = [c for c in val_df.columns if c not in ("quality", "quality_label")]

# Scale each feature individually
for feat in feature_cols:
    assembler = VectorAssembler(inputCols=[feat], outputCol=f"{feat}_vect")
    scaler = MinMaxScaler(inputCol=f"{feat}_vect", outputCol=f"{feat}_scaled")
    pipeline = Pipeline(stages=[assembler, scaler]) if False else None
    # Note: we fit scaler on validation data to match training preprocessing
    val_df = (Pipeline(stages=[assembler, scaler]).fit(val_df)
              .transform(val_df)
              .withColumn(f"{feat}_scaled", unlist(f"{feat}_scaled"))
              .drop(f"{feat}_vect").drop(feat))

# Assemble feature vector
scaled_feats = [f + "_scaled" for f in feature_cols]
vector_asm = VectorAssembler(inputCols=scaled_feats, outputCol="features")
val_df = vector_asm.transform(val_df)

# Load model
model = PipelineModel.load(model_path)

# Make predictions
if 'features' in val_df.columns:
    val_df = val_df.drop('features')
predictions = model.transform(val_df)
predictions.select("predictedLabel", "quality_label", "features").show(30)

# Evaluate
evaluator = MulticlassClassificationEvaluator(labelCol="indexedLabel", predictionCol="prediction")
accuracy = evaluator.evaluate(predictions, {evaluator.metricName: "accuracy"})
f1 = evaluator.evaluate(predictions, {evaluator.metricName: "f1"})

print(f"Accuracy: {accuracy:.4f}")
print(f"F1 Score: {f1:.4f}")

spark.stop()

