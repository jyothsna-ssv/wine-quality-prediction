import setuptools
from pyspark.sql import SparkSession
from pyspark.sql.functions import col, log, when, udf
from pyspark.sql.types import DoubleType
from pyspark.ml.feature import VectorAssembler, MinMaxScaler, StringIndexer, IndexToString
from pyspark.ml.classification import RandomForestClassifier
from pyspark.ml import Pipeline
from functools import reduce

# UDF to extract scaled vector value
unlist = udf(lambda x: float(list(x)[0]), DoubleType())

# Paths (modify as needed)
TRAIN_DATA_PATH = "s3://wine-ml-jk773/input-data/TrainingDataset.csv"
MODEL_OUTPUT_PATH = "s3://wine-ml-jk773/models/wine_rf_model"

spark = SparkSession.builder.appName('WineModelTraining').getOrCreate()

# Load and clean column names
train_df = spark.read.option("header", True).option("sep", ";").csv(TRAIN_DATA_PATH)
old_cols = train_df.columns
clean_cols = [c.replace('"', '') for c in old_cols]
train_df = reduce(lambda df, i: df.withColumnRenamed(old_cols[i], clean_cols[i]),
                  range(len(clean_cols)), train_df)

# Cast to double and remove duplicates
train_df = (train_df
            .select(*[col(c).cast("double").alias(c) for c in clean_cols])
            .distinct())

# Create categorical label
train_df = train_df.withColumn(
    "quality_label",
    when(col("quality") <= 4, "Low")
    .when(col("quality") <= 7, "Medium")
    .otherwise("High")
)

# Log-transform selected features
for feat in ("sulphates", "alcohol"):
    train_df = train_df.withColumn(f"log_{feat}", log(col(feat) + 1))

# Identify features to scale
feature_cols = [c for c in train_df.columns if c not in ("quality", "quality_label")]

# Scale each feature individually
for feat in feature_cols:
    assembler = VectorAssembler(inputCols=[feat], outputCol=f"{feat}_vect")
    scaler = MinMaxScaler(inputCol=f"{feat}_vect", outputCol=f"{feat}_scaled")
    pipeline = Pipeline(stages=[assembler, scaler])
    train_df = (pipeline.fit(train_df)
                .transform(train_df)
                .withColumn(f"{feat}_scaled", unlist(f"{feat}_scaled"))
                .drop(f"{feat}_vect").drop(feat))

# Assemble features vector
scaled_feats = [f + "_scaled" for f in feature_cols]
vector_asm = VectorAssembler(inputCols=scaled_feats, outputCol="features")

# Label indexing and model definition
indexer = StringIndexer(inputCol="quality_label", outputCol="indexedLabel")
rf = RandomForestClassifier(labelCol="indexedLabel", featuresCol="features", numTrees=200)
converter = IndexToString(inputCol="prediction", outputCol="predictedLabel", labels=indexer.fit(train_df).labels)

# Build pipeline
pipeline = Pipeline(stages=[indexer, vector_asm, rf, converter])

# Train and save model
model = pipeline.fit(train_df)
model.write().overwrite().save(MODEL_OUTPUT_PATH)

spark.stop()

